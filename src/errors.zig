/// The short reason stb_image gives for `err`, as `stbi_failure_reason`
/// returns it. For `UnknownPngChunk` stb_image puts the chunk's four letters
/// before the text; the reason here leaves them out.
pub fn failureReason(err: Error) []const u8 {
    return strings(err)[0];
}

/// The longer reason stb_image gives for `err` when built with
/// `STBI_FAILURE_USERMSG`.
pub fn failureMessage(err: Error) []const u8 {
    return strings(err)[1];
}

