fn cases(comptime call: fuzz.Call, comptime numbers: []const u32) [numbers.len]fuzz.Unsafe {
    var list: [numbers.len]fuzz.Unsafe = undefined;
    for (&list, numbers) |*entry, number| entry.* = .{ .case = number, .call = call };
    return list;
}
